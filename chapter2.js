    function openStep(i) {
        if (i < 0 || i >= STEPS.length) { openHub(); return; }
        if (i > curIndex()) { toast('Этот шаг откроется после предыдущего.'); return; }
        S.idx = i;
        resetTransient();
        renderStep(false);
        show('screen-c2-step');
    }

    function nextLabel(st) { return isLastOfPart(st) ? 'Завершить часть' : 'Дальше'; }

    function renderStep(keepScroll) {
        var st = STEPS[S.idx];
        var root = $('screen-c2-step');
        if (!st || !root) return;
        var part = PARTS[st.p - 1];
        var done = !!C.done[st.id];
        var list = stepsOfPart(st.p);
        var pos = list.indexOf(st) + 1;
        var h = illu(st.img || part.img, part.t);
        h += '<div class="paper-card">';
        h += '<div class="chapter-kicker">Часть ' + part.n + ' из 10 · ' + esc(part.t) + '</div>';
        h += '<h2>' + esc(st.title) + '</h2>';
        h += '<div class="c2-progress">Шаг ' + pos + ' из ' + list.length + '</div>';
        if (st.say) h += '<div class="c2-say"><b>Дариека:</b> «' + st.say + '»</div>';
        h += R[st.type](st, done);
        h += '<div id="c2fb" class="c2-fb ' + esc(S.msgCls) + '">' + S.msg + '</div>';
        S.msg = ''; S.msgCls = '';
        if (st.type === 'story' && !done) {
            h += '<button type="button" class="btn btn-gold" data-a="complete">' + esc(st.btn || 'Далее') + '</button>';
        } else if (done && st.type !== 'final') {
            h += '<button type="button" class="btn btn-gold" data-a="next">' + nextLabel(st) + '</button>';
        }
        h += '<button type="button" class="btn btn-back" data-a="hub">К расследованию</button>';
        h += '</div>';
        var y = window.pageYOffset || 0;
        root.innerHTML = h;
        if (keepScroll) window.scrollTo(0, y);
    }

