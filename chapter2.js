    function stepById(id) { for (var i = 0; i < STEPS.length; i++) if (STEPS[i].id === id) return STEPS[i]; return null; }
    function stepsOfPart(n) { return STEPS.filter(function (s) { return s.p === n; }); }
    function partDone(n) { return stepsOfPart(n).every(function (s) { return !!C.done[s.id]; }); }
    function curIndex() { for (var i = 0; i < STEPS.length; i++) if (!C.done[STEPS[i].id]) return i; return STEPS.length; }
    function doneCount() { return STEPS.filter(function (s) { return !!C.done[s.id]; }).length; }
    function isLastOfPart(st) { var l = stepsOfPart(st.p); return l[l.length - 1] === st; }
    function curPart() { var i = curIndex(); return i >= STEPS.length ? 10 : STEPS[i].p; }

    // Первый том считается завершённым, когда открыты ВСЕ страницы 0..N-1 (а не просто length === 11).
    function grimoireDone() {
        try {
            if (typeof grimoireLessons === 'undefined' || !Array.isArray(gameState.grimoirePages)) return false;
            for (var i = 0; i < grimoireLessons.length; i++) {
                if (gameState.grimoirePages.indexOf(i) === -1) return false;
            }
            return grimoireLessons.length > 0;
        } catch (e) { return false; }
    }
    function unlocked() { return grimoireDone(); }
    function stationOpen(s) { return !!C.done[s.unlock]; }
    // Шаг «Станции хранительницы» засчитывается, когда осмотрены все открытые станции (в шаге или на карте открытий)
    function stationsStepCheck() {
        var st = stepById('p5s1');
        if (!st || C.done[st.id] || STEPS.indexOf(st) > curIndex()) return;
        if (STATIONS.filter(stationOpen).every(function (x) { return C.visited[x.id]; })) complete(st.id);
    }
    function fragText(st, id) { for (var i = 0; i < st.frags.length; i++) if (st.frags[i].id === id) return st.frags[i].t; return ''; }
