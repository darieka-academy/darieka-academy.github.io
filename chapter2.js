    /* ----- обработчик нажатий внутри шага ----- */
    function stepAct(a, el) {
        var st = STEPS[S.idx];
        if (!st) return;
        var d = ans(st.id);
        var n;
        switch (a) {
            case 'hub': openHub(); return;
            case 'next':
                if (isLastOfPart(st)) openHub(); else openStep(S.idx + 1);
                return;
            case 'map': backToMap(); return;
            case 'complete':
                complete(st.id); renderStep(false); return;

            case 'clue': {
                var id = el.getAttribute('data-id');
                d.found = d.found || [];
                if (d.found.indexOf(id) < 0) { d.found.push(id); persist(); }
                S.clue = id;
                if (d.found.length >= st.clues.length && !C.done[st.id]) { say('Все улики найдены!', true); complete(st.id); }
                break;
            }
            case 'ans': {
                var qi = parseInt(el.getAttribute('data-q'), 10), o = parseInt(el.getAttribute('data-o'), 10), q = st.qs[qi];
                if (!q || (d.i || 0) !== qi) return;
                if (o === q.ok) {
                    d.i = qi + 1; persist(); S.bad = {};
                    say('Верно!', true);
                    if (d.i >= st.qs.length) complete(st.id);
                } else {
                    S.bad[qi + ':' + o] = true;
                    say(q.hint, false);
                }
                break;
            }
            case 'mL': {
                d.m = d.m || {};
                var lid = el.getAttribute('data-id');
                if (d.m[lid]) return;
                S.sel = lid;
                break;
            }
            case 'mR': {
                d.m = d.m || {};
                var rid = el.getAttribute('data-id');
                if (!S.sel) { say('Сначала выбери запись в первом списке.', false); break; }
                if (rid === S.sel) {
                    d.m[rid] = true; persist(); S.sel = null;
                    say('Верно!', true);
                    if (st.left.every(function (l) { return d.m[l.id]; })) complete(st.id);
                } else {
                    say('Не сходится — выбери другую пару.', false);
                }
                break;
            }
            case 'sortset': {
                d.s = d.s || {};
                d.s[el.getAttribute('data-id')] = el.getAttribute('data-g');
                S.wrongIds[el.getAttribute('data-id')] = false;
                persist();
                break;
            }
            case 'sortcheck': {
                d.s = d.s || {};
                S.wrongIds = {};
                var missing = 0, wrong = 0;
                st.items.forEach(function (it) {
                    if (!d.s[it.id]) missing++;
                    else if (d.s[it.id] !== it.g) { wrong++; S.wrongIds[it.id] = true; }
                });
                if (missing) say('Распредели все карточки — осталось: ' + missing + '.', false);
                else if (wrong) say('Не всё на месте: отмечено карточек — ' + wrong + '. Подумай ещё.', false);
                else { say('Всё верно!', true); complete(st.id); }
                break;
            }
            case 'ord': {
                d.o = d.o || [];
                var fid = el.getAttribute('data-id');
                if (d.o.indexOf(fid) > -1) return;
                d.o.push(fid); persist();
                if (d.o.length === st.order.length) {
                    if (d.o.join(',') === st.order.join(',')) { say('Запись собрана!', true); complete(st.id); }
                    else say('Порядок пока не сходится. Убери последний фрагмент или начни заново.', false);
                }
                break;
            }
            case 'ordundo': d.o = d.o || []; d.o.pop(); persist(); break;
            case 'ordreset': d.o = []; persist(); break;
            case 'pick': {
                d.p = d.p || [];
                var pid = el.getAttribute('data-id'), pi = d.p.indexOf(pid);
                if (pi > -1) d.p.splice(pi, 1); else d.p.push(pid);
                persist();
                break;
            }
            case 'pickcheck': {
                d.p = d.p || [];
                if (!d.p.length) { say('Отметь хотя бы одно утверждение.', false); break; }
                var good = d.p.filter(function (x) { return st.correct.indexOf(x) > -1; }).length;
                var extra = d.p.length - good;
                if (good === st.correct.length && !extra) { say('Верно!', true); complete(st.id); }
                else if (extra) say('Есть лишние отметки. Найдено верно: ' + good + ' из ' + st.correct.length + '.', false);
                else say('Найдено верно: ' + good + ' из ' + st.correct.length + '. Поищи ещё.', false);
                break;
            }
            case 'fopt': {
                d.f = d.f || {};
                d.f[el.getAttribute('data-f')] = parseInt(el.getAttribute('data-o'), 10);
                delete S.badF[el.getAttribute('data-f')];
                persist();
                break;
            }
            case 'fcheck': {
                d.f = d.f || {};
                S.badF = {};
                var empty = 0, bad = 0;
                st.fields.forEach(function (fd) {
                    if (d.f[fd.id] === undefined) { empty++; S.badF[fd.id] = true; }
                    else if (d.f[fd.id] !== fd.ok) { bad++; S.badF[fd.id] = true; }
                });
                if (empty) say('Заполни все строки карточки.', false);
                else if (bad) say('Не всё сходится — строки с ошибкой отмечены. Вспомни наблюдения.', false);
                else { say('Карточка собрана!', true); complete(st.id); }
                break;
            }
            case 'stvisit': {
                var sid = el.getAttribute('data-id'), s = null;
                STATIONS.forEach(function (x) { if (x.id === sid) s = x; });
                if (!s) return;
                if (!stationOpen(s)) { toast(s.lockText); return; }
                C.visited[sid] = true; persist(); S.station = sid;
                var wasDone = !!C.done[st.id];
                stationsStepCheck();
                if (!wasDone && C.done[st.id]) say('Все открытые станции осмотрены!', true);
                break;
            }
            case 'chest': {
                say('Три знака сошлись — сундук открылся!', true);
                complete(st.id);
                break;
            }
            case 'door': playArchiveDoor(function () { openTeaser(); }); return;
            default: return;
        }
        renderStep(true);
    }

