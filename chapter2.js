    function buildArchive() {
        var out = [];
        STEPS.forEach(function (st) {
            if (!C.done[st.id]) return;
            if (st.archClues) {
                var found = (C.ans[st.id] && C.ans[st.id].found) || [];
                st.clues.forEach(function (c) { if (found.indexOf(c.id) > -1) out.push({ t: c.t, x: c.x }); });
            }
            if (st.arch) {
                var x = st.arch.x;
                if (st.arch.from === 'order') x = st.order.map(function (id) { return fragText(st, id); }).join(' ');
                out.push({ t: st.arch.t, x: x });
            }
        });
        return out;
    }

