    var pager = { page: 0, restoring: false };

    function initPager() {
        var track = $('mapTrack'), prev = $('mapPrev'), next = $('mapNext'), dots = $('mapDots'), title = $('mapPagerTitle'), mapEl = $('screen-map');
        if (!track || !mapEl) return;
        var slides = track.querySelectorAll('.map-slide');
        var total = slides.length || 3;

        function sync() {
            var dl = dots ? dots.querySelectorAll('.map-dot') : [];
            for (var i = 0; i < dl.length; i++) dl[i].classList.toggle('active', i === pager.page);
            if (title && slides[pager.page]) title.textContent = slides[pager.page].getAttribute('data-title') || '';
            if (prev) prev.setAttribute('aria-disabled', pager.page <= 0 ? 'true' : 'false');
            if (next) next.setAttribute('aria-disabled', pager.page >= total - 1 ? 'true' : 'false');
        }
        function go(p, smooth) {
            p = Math.max(0, Math.min(total - 1, p));
            pager.page = p;
            var left = p * track.clientWidth;
            if (typeof track.scrollTo === 'function') track.scrollTo({ left: left, behavior: smooth ? 'smooth' : 'auto' });
            else track.scrollLeft = left;
            sync();
        }
        if (prev) prev.addEventListener('click', function () { go(pager.page - 1, true); });
        if (next) next.addEventListener('click', function () { go(pager.page + 1, true); });
        if (dots) dots.addEventListener('click', function (e) {
            var b = e.target.closest ? e.target.closest('.map-dot') : null;
            if (b) go(parseInt(b.getAttribute('data-p'), 10) || 0, true);
        });
        track.addEventListener('scroll', function () {
            if (pager.restoring) return;
            var w = track.clientWidth;
            if (!w) return;
            var p = Math.round(track.scrollLeft / w);
            if (p !== pager.page) { pager.page = Math.max(0, Math.min(total - 1, p)); sync(); }
        }, { passive: true });
        window.addEventListener('resize', function () { if (mapEl.classList.contains('active')) track.scrollLeft = pager.page * track.clientWidth; });
        document.addEventListener('keydown', function (e) {
            if (!mapEl.classList.contains('active')) return;
            var t = e.target;
            if (t && /^(INPUT|TEXTAREA|SELECT)$/.test(t.tagName)) return;
            if (e.key === 'ArrowLeft') { go(pager.page - 1, true); e.preventDefault(); }
            else if (e.key === 'ArrowRight') { go(pager.page + 1, true); e.preventDefault(); }
        });

        // Возврат на карту: браузер сбрасывает прокрутку скрытого блока — восстанавливаем выбранную страницу.
        if (typeof MutationObserver === 'function') {
            new MutationObserver(function () {
                if (!mapEl.classList.contains('active')) return;
                pager.restoring = true;
                requestAnimationFrame(function () {
                    track.scrollLeft = pager.page * track.clientWidth;
                    sync();
                    setTimeout(function () { pager.restoring = false; }, 80);
                });
            }).observe(mapEl, { attributes: true, attributeFilter: ['class'] });
        }
        // Клики по плиткам страниц 2 и 3
        track.addEventListener('click', function (e) {
            var el = e.target.closest ? e.target.closest('.c2-tile[data-a]') : null;
            if (el) genericAct(el.getAttribute('data-a'), el);
        });
        sync();
    }

