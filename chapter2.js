    function reward(key, exp) {
        if (C.claimed[key]) return false;
        C.claimed[key] = true;
        persist();                 // сначала помечаем награду полученной
        gameState.exp += exp;
        saveState();               // saveState -> updateUI -> ch2UpdateUI (ничего не сохраняет, цикла нет)
        return true;
    }

    function complete(stepId) {
        var st = stepById(stepId);
        if (!st || C.done[stepId]) return;
        C.done[stepId] = true;
        (st.grant || []).forEach(function (g) { if (C.items.indexOf(g) < 0) C.items.push(g); });
        if (stepId === 'p10s2') C.finished = true;
        persist();
        var got = false;
        if (partDone(st.p)) {
            var exp = st.p === 10 ? 50 : 15;
            if (reward('p' + st.p, exp)) { got = true; toast('Часть ' + st.p + ' завершена · +' + exp + ' опыта'); }
        }
        if (!got) updateUI();       // обновить счётчик находок и карту
    }

