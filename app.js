function closeModal() {
  const modal = document.getElementById('modal');

  if (!modal || modal.hidden) return;

  modal.hidden = true;
  modalConfig = null;
  document.body.classList.remove('modal-open');

  if (modalReturnFocus && typeof modalReturnFocus.focus === 'function') {
    try { modalReturnFocus.focus(); } catch (e) {}
  }
}

function submitModal() {
  if (!modalConfig) return;

  const result = modalConfig.onSubmit(
    document.getElementById('modalInput').value
  );

  if (typeof result === 'string') {
    document.getElementById('modalError').textContent = result;
    return;
  }

  closeModal();
}

function initModal() {
  const modal = document.getElementById('modal');

  document.getElementById('modalCheck').addEventListener('change', event => {
    document.getElementById('modalOk').disabled = !event.target.checked;
  });

  document.getElementById('modalInput').addEventListener('keydown', event => {
    if (event.key === 'Enter') {
      event.preventDefault();
      submitModal();
    }
  });

  document.addEventListener('keydown', event => {
    if (event.key === 'Escape' && !modal.hidden) {
      event.preventDefault();
      closeModal();
    }
  });

  modal.addEventListener('keydown', event => {
    if (event.key !== 'Tab') return;

    const focusable = [...modal.querySelectorAll('input,button')]
      .filter(el => !el.disabled && el.offsetParent !== null);

    if (!focusable.length) return;

    const first = focusable[0];
    const last = focusable[focusable.length - 1];

    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  });
}

