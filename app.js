function renderLessonRows(lessons, collection) {
  return lessons.map((lesson, index) => {
    const done = isCompleted(collection, index);
    const unlocked = index === 0 || isCompleted(collection, index - 1);

    const action = collection.startsWith('s')
      ? `openSectionLesson(${Number(collection.slice(1))},${index})`
      : `openChapterLesson(${Number(collection.slice(1))},${index})`;

    return `
      <button class="lesson-row ${done ? 'done' : ''}"
        ${unlocked ? `onclick="${action}"` : 'disabled'}>
        <span class="lesson-number">${done ? '✓' : index + 1}</span>
        <span>
          <b>${esc(lesson.title)}</b>
          <small>${esc(lesson.subtitle || '')}</small>
        </span>
        <em>${done ? 'Пройдено' : unlocked ? 'Открыть' : 'Закрыто'}</em>
      </button>
    `;
  }).join('');
}

