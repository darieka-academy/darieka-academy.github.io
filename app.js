function renderCheckArea() {
  const area = document.getElementById('checkArea');
  const quiz = currentLesson.quiz;

  if (quiz.type === 'choice') {
    area.innerHTML = quiz.options.map((value, index) => `
      <button class="choice-option ${checkState.selected === index ? 'selected' : ''}"
        onclick="chooseCheckOption(${index})">
        <span class="choice-marker">${String.fromCharCode(1040 + index)}</span>
        <span>${esc(value)}</span>
      </button>
    `).join('');
  }

  else if (quiz.type === 'sequence') {
    area.innerHTML = `
      <p class="quiet">Нажимай на пункты в нужном порядке. Если передумала, нажми на выбранный пункт ещё раз.</p>
      <div class="sequence-list">
        ${quiz.items.map((value, index) => {
          const position = checkState.sequence.indexOf(index);

          return `
            <button class="sequence-option ${position >= 0 ? 'selected' : ''}"
              onclick="toggleSequence(${index})">
              <span class="choice-marker">${position >= 0 ? position + 1 : '·'}</span>
              <span>${esc(value)}</span>
              <em>${position >= 0 ? 'Выбрано' : 'Добавить'}</em>
            </button>
          `;
        }).join('')}
      </div>
    `;
  }

  else if (quiz.type === 'matching') {
    const rights = quiz.pairs.map(pair => pair.right);

    area.innerHTML = quiz.pairs.map((pair, index) => `
      <div class="match-row">
        <label>${esc(pair.left)}</label>
        <select onchange="setMatch(${index},this.value)">
          <option value="">Выбери соответствие</option>
          ${rights.map((right, rightIndex) => `
            <option value="${rightIndex}"
              ${checkState.matches[index] === String(rightIndex) ? 'selected' : ''}>
              ${esc(right)}
            </option>
          `).join('')}
        </select>
      </div>
    `).join('');
  }

  else if (quiz.type === 'multiple') {
    area.innerHTML = quiz.options.map((value, index) => `
      <label class="choice-option">
        <input type="checkbox" value="${index}"
          ${checkState.multiple.includes(index) ? 'checked' : ''}
          onchange="toggleMultiple(${index},this.checked)">
        <span>${esc(value)}</span>
      </label>
    `).join('');
  }
}

function chooseCheckOption(index) {
  checkState.selected = index;
  renderCheckArea();
}

function toggleSequence(index) {
  const position = checkState.sequence.indexOf(index);

  if (position >= 0) {
    checkState.sequence.splice(position, 1);
  } else {
    checkState.sequence.push(index);
  }

  renderCheckArea();
}

function setMatch(index, value) {
  checkState.matches[index] = value;
}

function toggleMultiple(index, checked) {
  if (checked && !checkState.multiple.includes(index)) {
    checkState.multiple.push(index);
  }

  if (!checked) {
    checkState.multiple = checkState.multiple.filter(value => value !== index);
  }
}

function sameArray(a, b) {
  return a.length === b.length && a.every((value, index) => value === b[index]);
}

function evaluateCheck() {
  const quiz = currentLesson.quiz;

  if (quiz.type === 'choice') {
    return checkState.selected === quiz.answer;
  }

  if (quiz.type === 'sequence') {
    return sameArray(checkState.sequence, quiz.answer);
  }

  if (quiz.type === 'matching') {
    return quiz.pairs.every((pair, index) => {
      const selectedIndex = Number(checkState.matches[index]);

      return checkState.matches[index] !== undefined &&
        selectedIndex === index &&
        quiz.pairs[selectedIndex]?.right === pair.right;
    });
  }

  if (quiz.type === 'multiple') {
    return sameArray(
      [...checkState.multiple].sort((a, b) => a - b),
      [...quiz.answer].sort((a, b) => a - b)
    );
  }

  return false;
}

function submitCheck() {
  if (!checkState || !currentLesson) return;

  const quiz = currentLesson.quiz;

  const missing =
    (quiz.type === 'choice' && checkState.selected === null) ||
    (quiz.type === 'sequence' && checkState.sequence.length !== quiz.items.length) ||
    (quiz.type === 'matching' && Object.keys(checkState.matches).length !== quiz.pairs.length) ||
    (quiz.type === 'multiple' && checkState.multiple.length === 0);

  if (missing) {
    document.getElementById('checkFeedback').textContent =
      'Сначала выбери ответ или заполни все пары.';
    document.getElementById('checkFeedback').className = 'feedback try';
    return;
  }

  if (evaluateCheck()) {
    document.getElementById('checkFeedback').textContent =
      'Верно! Дариека одобрительно кивает.';
    document.getElementById('checkFeedback').className = 'feedback good';
    document.getElementById('checkSubmit').hidden = true;

    completeLesson();
  } else {
    document.getElementById('checkFeedback').textContent =
      'Пока не получилось. Вернись к объяснению и попробуй ещё раз.';
    document.getElementById('checkFeedback').className = 'feedback try';
    document.getElementById('checkSubmit').hidden = true;
    document.getElementById('checkRetry').hidden = false;
  }
}

