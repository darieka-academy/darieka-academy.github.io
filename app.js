function syncMapUI() {
  for (let i = 0; i < MAP_PAGES; i++) {
    const tab = document.getElementById(`mapTab${i}`);
    if (!tab) continue;

    tab.setAttribute('aria-selected', i === mapPage ? 'true' : 'false');
    tab.tabIndex = i === mapPage ? 0 : -1;
  }

  document.getElementById('mapPrev').disabled = mapPage === 0;
  document.getElementById('mapNext').disabled = mapPage === MAP_PAGES - 1;
  document.getElementById('mapHint').hidden = !!state.ui.mapSwiped;
}

function setMapPage(index, smooth) {
  const pager = getPager();
  if (!pager) return;

  mapPage = Math.max(0, Math.min(MAP_PAGES - 1, index));

  if (smooth) autoScrollUntil = Date.now() + 700;

  if (pager.clientWidth) {
    pager.scrollTo({
      left: mapPage * pager.clientWidth,
      behavior: smooth ? 'smooth' : 'auto'
    });
  }

  syncMapUI();
}

function rememberMapPage() {
  if (state.ui.mapPage !== mapPage) {
    state.ui.mapPage = mapPage;
    persist();
  }
}

function markMapSwiped() {
  if (!state.ui.mapSwiped) {
    state.ui.mapSwiped = true;
    persist();
    syncMapUI();
  }
}

function goMapPage(index) {
  setMapPage(index, true);
  rememberMapPage();
  markMapSwiped();
}

function mapStep(delta) {
  goMapPage(mapPage + delta);
}

function restoreMapPage() {
  mapPage = [0, 1, 2].includes(state.ui.mapPage)
    ? state.ui.mapPage
    : 0;

  setMapPage(mapPage, false);
}

function onMapScroll() {
  const pager = getPager();
  if (!pager || !pager.clientWidth) return;

  if (Date.now() < autoScrollUntil) {
    clearTimeout(settleTimer);
    settleTimer = setTimeout(
      onMapScroll,
      autoScrollUntil - Date.now() + 40
    );
    return;
  }

  const index = Math.max(
    0,
    Math.min(
      MAP_PAGES - 1,
      Math.round(pager.scrollLeft / pager.clientWidth)
    )
  );

  if (index !== mapPage) {
    mapPage = index;
    syncMapUI();
    rememberMapPage();
    markMapSwiped();
  }
}

function initMapPager() {
  const pager = getPager();
  if (!pager) return;

  let frame = 0;

  pager.addEventListener('scroll', () => {
    if (frame) return;

    frame = requestAnimationFrame(() => {
      frame = 0;
      onMapScroll();
    });
  }, { passive: true });

  let drag = null;

  pager.addEventListener('pointerdown', event => {
    if (event.pointerType !== 'mouse' || event.button !== 0) return;

    drag = {
      x: event.clientX,
      left: pager.scrollLeft,
      page: mapPage,
      moved: false,
      id: event.pointerId
    };
  });

  pager.addEventListener('pointermove', event => {
    if (!drag || event.pointerId !== drag.id) return;

    const dx = event.clientX - drag.x;

    if (!drag.moved && Math.abs(dx) > 6) {
      drag.moved = true;
      pager.classList.add('dragging');

      try { pager.setPointerCapture(drag.id); } catch (err) {}
    }

    if (drag.moved) {
      pager.scrollLeft = drag.left - dx;
    }
  });

  function endDrag(event) {
    if (!drag || event.pointerId !== drag.id) return;

    const old = drag;
    drag = null;

    if (!old.moved) return;

    pager.classList.remove('dragging');

    try { pager.releasePointerCapture(old.id); } catch (err) {}

    suppressMapClickUntil = Date.now() + 120;

    const dx = event.clientX - old.x;
    const threshold = pager.clientWidth * 0.12;

    goMapPage(
      dx < -threshold
        ? old.page + 1
        : dx > threshold
          ? old.page - 1
          : old.page
    );
  }

  pager.addEventListener('pointerup', endDrag);
  pager.addEventListener('pointercancel', endDrag);

  pager.addEventListener('click', event => {
    if (Date.now() < suppressMapClickUntil) {
      event.preventDefault();
      event.stopPropagation();
    }
  }, true);

  pager.addEventListener('dragstart', event => {
    event.preventDefault();
  });

  document.addEventListener('keydown', event => {
    if (!['ArrowLeft', 'ArrowRight'].includes(event.key)) return;

    if (
      !document.getElementById('screen-home').classList.contains('active') ||
      !document.getElementById('modal').hidden
    ) {
      return;
    }

    const tag = (event.target && event.target.tagName || '').toLowerCase();

    if (tag === 'input' || tag === 'textarea' || tag === 'select') return;

    event.preventDefault();
    mapStep(event.key === 'ArrowLeft' ? -1 : 1);
  });

  window.addEventListener('resize', () => {
    setMapPage(mapPage, false);
  });
}

