function renderLessonStep() {
  if (!currentLesson) return;
  const pages = currentLesson.flowPages || [];
  const body = document.getElementById('lessonBody');
  const title = document.getElementById('lessonTitle');
  const button = document.getElementById('lessonNextButton');
  const image = document.getElementById('lessonImage');
  const note = document.getElementById('lessonNote');

  if (currentLessonStep === 0) {
    title.textContent = currentLesson.title;
    body.innerHTML = currentLesson.body || '';
    note.textContent = currentLesson.note || 'Дариека: «Записывай то, что заметила, и не бойся задавать вопросы».';
    image.hidden = !currentLesson.image;
    if (currentLesson.image) image.src = currentLesson.image;
  } else {
    const page = pages[currentLessonStep - 1];
    if (!page) return;
    title.textContent = page.title || currentLesson.title;
    body.innerHTML = page.body || '';
    note.textContent = page.note || currentLesson.note || '';
    image.hidden = true;
  }

  const total = pages.length + 1;
  const isLast = currentLessonStep >= total - 1;
  button.textContent = !isLast
    ? 'Следуй дальше'
    : currentLesson.noQuiz
      ? 'Следуй дальше'
      : 'Проверь полученные знания';

  let indicator = document.getElementById('lessonStepIndicator');
  if (!indicator) {
    indicator = document.createElement('p');
    indicator.id = 'lessonStepIndicator';
    indicator.className = 'lesson-step-indicator';
    body.parentNode.insertBefore(indicator, body);
  }
  indicator.textContent = total > 1
    ? `Страница ${currentLessonStep + 1} из ${total}`
    : '';
  indicator.hidden = total <= 1;
}

function nextLessonStep() {
  if (!currentLesson) return;
  const pages = currentLesson.flowPages || [];
  if (currentLessonStep < pages.length) {
    currentLessonStep += 1;
    renderLessonStep();
    window.scrollTo({ top: 0, behavior: 'smooth' });
    return;
  }

  const practiceInput = document.getElementById('practiceInput');
  if (practiceInput && currentLessonKey) {
    state.practiceNotes[currentLessonKey] = practiceInput.value.trim();
    persist();
  }

  if (currentLesson.noQuiz) {
    completeLessonQuietly();
  } else {
    startCheck();
  }
}

function completeLessonQuietly() {
  const ref = getLessonByKey(currentLessonKey);
  if (!ref) return;
  const list = state.completed[ref.collection];
  if (!list.includes(ref.index)) {
    list.push(ref.index);
    list.sort((a, b) => a - b);
    state.exp += 10;
  }
  if (!state.bookEntries.includes(currentLessonKey)) state.bookEntries.push(currentLessonKey);
  if (ref.lesson.sealId && !state.seals.includes(ref.lesson.sealId)) {
    state.seals.push(ref.lesson.sealId);
  }
  persist();

  const nextIndex = ref.index + 1;
  const total = ref.collection.startsWith('s')
    ? SECTIONS[ref.section].lessons.length
    : CHAPTERS[ref.chapter - 1].lessons.length;

  if (nextIndex < total) {
    if (ref.section != null) openSectionLesson(ref.section, nextIndex);
    else openChapterLesson(ref.chapter, nextIndex);
    return;
  }

  // Последняя страница без отдельного теста: завершаем блок и не отправляем
  // ученицу обратно к списку уроков.
  if (ref.section === 0) {
    openSection(1);
    openSectionLesson(1, 0);
  } else if (ref.section === 1) {
    openChapter(1);
    openChapterLesson(2, 0);
  } else if (ref.chapter && ref.chapter < 4) {
    openChapter(ref.chapter);
    openChapterLesson(ref.chapter + 1, 0);
  } else {
    showScreen('home');
    toast('Материал прочитан. Дариека ждёт тебя на карте Академии.');
  }
}

