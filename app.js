function normalizeState(raw) {
  const s = raw && typeof raw === 'object' ? raw : {};
  const old = s.completed && typeof s.completed === 'object' ? s.completed : {};
  const familiarIds = ASSETS.familiars.map(f => f.id);
  const out = defaultState();

  out.version = SAVE_VERSION;
  out.name = cleanInput(s.name, NAME_MAX);
  out.familiarId = familiarIds.includes(s.familiarId) ? s.familiarId : '';
  out.familiarName = cleanInput(s.familiarName, FAMILIAR_NAME_MAX);
  out.exp = Math.max(0, parseInt(s.exp, 10) || 0);

  out.completed = {
    s0: validIndexes(old.s0 !== undefined ? old.s0 : old[0], 5),
    s1: validIndexes(old.s1 !== undefined ? old.s1 : old[1], 5),
    c2: validIndexes(old.c2, 6),
    c3: validIndexes(old.c3, 5),
    c4: validIndexes(old.c4, 5)
  };

  out.seals = Array.isArray(s.seals)
    ? [...new Set(s.seals.map(Number).filter(n => n >= 1 && n <= 10))]
    : [];

  out.diplomaAwarded = s.diplomaAwarded === true || out.completed.s0.length === 5;

  out.bookEntries = Array.isArray(s.bookEntries)
    ? [...new Set(s.bookEntries.filter(v => typeof v === 'string'))]
    : [];

  out.practiceNotes = s.practiceNotes && typeof s.practiceNotes === 'object'
    ? s.practiceNotes
    : {};

  if (s.notes && typeof s.notes === 'object') {
    out.notes.travnik = typeof s.notes.travnik === 'string' ? s.notes.travnik : '';
    out.notes.grimoire = typeof s.notes.grimoire === 'string' ? s.notes.grimoire : '';
  } else if (typeof s.notes === 'string') {
    out.notes.grimoire = s.notes;
  }

  const ui = s.ui && typeof s.ui === 'object' ? s.ui : {};
  out.ui = {
    mapPage: [0, 1, 2].includes(ui.mapPage) ? ui.mapPage : 0,
    mapSwiped: !!ui.mapSwiped
  };

  return out;
}

function loadState() {
  const rawV2 = lsGet(STORE_V2);
  const parsed = parseObject(rawV2);

  if (parsed) return normalizeState(parsed);

  if (rawV2 && !lsGet(STORE_CORRUPT)) {
    lsSet(STORE_CORRUPT, rawV2);
  }

  const v1 = parseObject(lsGet(STORE_V1));
  const legacyName = lsGet('darieka_student_name') || '';
  const base = v1 || {
    name: legacyName,
    exp: parseInt(lsGet('darieka_exp') || '0', 10) || 0
  };

  if (!base.name) base.name = legacyName;
  return normalizeState(base);
}

function lessonKeyForSection(section, index) {
  return `s${section}_${index}`;
}

function lessonKeyForChapter(chapter, index) {
  return `c${chapter}_${index}`;
}

function getLessonByKey(key) {
  let match = key.match(/^s([01])_(\d+)$/);

  if (match) {
    const section = Number(match[1]);
    const index = Number(match[2]);
    const lesson = SECTIONS[section].lessons[index];

    return lesson ? {
      lesson,
      book: SECTIONS[section].book,
      collection: `s${section}`,
      index,
      chapter: 0,
      section
    } : null;
  }

  match = key.match(/^c([234])_(\d+)$/);

  if (match) {
    const chapter = Number(match[1]);
    const index = Number(match[2]);
    const lesson = CHAPTERS[chapter - 1].lessons[index];

    return lesson ? {
      lesson,
      book: lesson.book,
      collection: `c${chapter}`,
      index,
      chapter,
      section: null
    } : null;
  }

  return null;
}

function getCompletedList(collection) {
  return state.completed[collection] || [];
}

function isCompleted(collection, index) {
  return getCompletedList(collection).includes(index);
}

function hydrateBookEntries() {
  Object.keys(state.completed).forEach(collection => {
    state.completed[collection].forEach(index => {
      let key = '';

      if (collection === 's0' || collection === 's1') {
        key = `s${collection.slice(1)}_${index}`;
      } else {
        key = `${collection}_${index}`;
      }

      const ref = getLessonByKey(key);

      if (ref && !state.bookEntries.includes(key)) {
        state.bookEntries.push(key);
      }

      if (ref && ref.lesson.sealId && !state.seals.includes(ref.lesson.sealId)) {
        state.seals.push(ref.lesson.sealId);
      }
    });
  });
}

