function completeLesson() {
  const ref = getLessonByKey(currentLessonKey);
  if (!ref) return;

  const list = state.completed[ref.collection];
  const isNew = !list.includes(ref.index);

  if (isNew) {
    list.push(ref.index);
    list.sort((a, b) => a - b);
    state.exp += 20;
  }

  if (
    ref.collection === 's0' &&
    list.length === 5 &&
    !state.diplomaAwarded
  ) {
    state.exp += 50;
    state.diplomaAwarded = true;
  }

  if (!state.bookEntries.includes(currentLessonKey)) {
    state.bookEntries.push(currentLessonKey);
  }

  if (ref.lesson.sealId && !state.seals.includes(ref.lesson.sealId)) {
    state.seals.push(ref.lesson.sealId);
  }

  persist();
  showReward(ref, isNew);
}

